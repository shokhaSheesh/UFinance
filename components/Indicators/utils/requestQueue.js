/**
 * Последовательная очередь запросов страницы «Показатели».
 *
 * На странице десяток тяжёлых отчётов, и каждый график раньше уходил в сеть
 * сразу при монтировании — бэкенд получал все запросы одной пачкой. Здесь
 * задачи выстраиваются в цепочку: следующий запрос стартует только после того,
 * как пришёл ответ на предыдущий (успешный или нет).
 *
 * Порядок = порядок вызова, то есть порядок блоков на странице. Работает и для
 * повторных запросов при смене фильтров — они тоже идут друг за другом.
 *
 * Использование:
 *   queryFn: () => enqueueIndicatorRequest(() => apiClient.invokeFunction({...}))
 */

let tail = Promise.resolve()

export const enqueueIndicatorRequest = (task) => {
  // и на успехе, и на ошибке продолжаем цепочку — иначе одна упавшая
  // задача заблокировала бы очередь навсегда
  const run = tail.then(task, task)
  tail = run.then(
    () => undefined,
    () => undefined
  )
  return run
}
